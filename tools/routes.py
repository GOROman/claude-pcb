"""配線・ビア・ベタの定義。gen_pcb.Gen のメソッドを使って描く。

座標は基板左上原点の mm。チップ U1 は (10.5, 25.1)。
QFN の辺の中ほどにある電源ピンと一部の信号は、パッド列と中央 GND パッドの間（チップの真下）にビアを打って内層・裏面へ落とす。
"""
import pcbnew

F, B = pcbnew.F_Cu, pcbnew.B_Cu
W, H = 21.0, 51.0


def build(g):
    U = lambda n: g.pad("U1", n)
    J = lambda n: g.pad("J2", n)
    P = g.pad
    gp = lambda n: "GPIO%d" % n
    gpio_pin = {0: 2, 1: 3, 2: 4, 3: 5, 4: 7, 5: 8, 6: 9, 7: 10, 8: 12, 9: 13, 10: 14, 11: 15, 12: 16, 13: 17,
                14: 18, 15: 19, 16: 27, 17: 28, 18: 29, 19: 31, 20: 32, 21: 33, 22: 34, 23: 35, 24: 36, 25: 37,
                26: 40, 27: 41, 28: 42, 29: 43}
    hdr = {n: i + 1 for i, n in enumerate(__import__("design").PICO_PINS) if n.startswith("GPIO")}
    UG = lambda n: U(gpio_pin[n])
    HG = lambda n: J(hdr[gp(n)])

    # ================================================= 左辺: GPIO0-7 は上へ（下のパッドほど外側の列）
    cols = {7: 2.75, 6: 3.05, 5: 3.35, 4: 3.65, 3: 3.95, 2: 4.25, 1: 4.55, 0: 4.85}
    for n in (2, 3, 4, 5, 6, 7):
        (px, py), (hx, hy), xc = UG(n), HG(n), cols[n]
        g.route(gp(n), [(px, py), (xc, py - 0.3), (xc, hy + 0.4), "ds", (hx, hy)])
    # GPIO0/1 は GPIO2 を抜けた後、左上の部品スペースを空けるため左へ寄せる
    (px, py), (hx, hy) = UG(1), HG(1)
    g.route(gp(1), [(px, py), (4.55, py - 0.3), (4.55, 8.5), "ds", (2.75, 6.7), (2.75, hy + 0.5), "ds", (hx, hy)])
    (px, py), (hx, hy) = UG(0), HG(0)
    g.route(gp(0), [(px, py), (4.85, py - 0.3), (4.85, 8.2), "ds", (3.05, 6.4), (3.05, hy + 0.6), "ds", (hx, hy)])

    # ================================================= 左辺: GPIO8 はほぼ真横、GPIO9-11 と下辺 GPIO12-15 は下へ
    (px, py), (hx, hy) = UG(8), HG(8)
    g.route(gp(8), [(px, py), (6.4, py), "ds", (5.95, 27.15), (3.0, 27.15), "sd", (hx, hy)])
    for n, yh, xc in ((9, 27.45, 2.75), (10, 27.75, 3.05), (11, 28.05, 3.35)):
        (px, py), (hx, hy) = UG(n), HG(n)
        g.route(gp(n), [(px, py), (6.4, py), "ds", (6.4 - (yh - py), yh), (xc + 0.3, yh), "ds", (xc, yh + 0.3),
                        (xc, hy - 0.4), "ds", (hx, hy)])
    for n, yh, xc in ((12, 29.95, 3.65), (13, 30.25, 3.95), (14, 30.55, 4.25)):
        (px, py), (hx, hy) = UG(n), HG(n)
        g.route(gp(n), [(px, py), (px, yh - 0.3), "ds", (px - 0.3, yh), (xc + 0.3, yh), "ds", (xc, yh + 0.3),
                        (xc, hy - 0.4), "ds", (hx, hy)])
    (px, py), (hx, hy) = UG(15), HG(15)  # GPIO15 は取付穴 H1 を左に避ける
    g.route(gp(15), [(px, py), (px, 30.55), "ds", (px - 0.3, 30.85), (4.85, 30.85), "ds", (4.55, 31.15),
                     (4.55, 46.9), "ds", (3.2, 48.25), (3.2, hy - 0.5), "ds", (hx, hy)])

    # ================================================= 右辺: GPIO26-28 は上へ、GPIO19-22 と下辺 GPIO16-18 は下へ
    (px, py), (hx, hy) = UG(26), HG(26)
    g.route(gp(26), [(px, py), (14.5, py), "ds", (14.75, 24.05), (18.6, 24.05), "-", (hx, hy)])
    for n, yh, xc in ((27, 23.75, 17.9), (28, 23.45, 17.6)):
        (px, py), (hx, hy) = UG(n), HG(n)
        g.route(gp(n), [(px, py), (14.5, py), "ds", (14.5 + (py - yh), yh), (xc - 0.3, yh), "ds", (xc, yh - 0.3),
                        (xc, hy + 0.4), "ds", (hx, hy)])
    for n, yh, xc in ((22, 27.45, 18.25), (21, 27.75, 17.95), (20, 28.05, 17.65), (19, 28.35, 17.35)):
        (px, py), (hx, hy) = UG(n), HG(n)
        g.route(gp(n), [(px, py), (14.45, py), "ds", (14.45 + (yh - py), yh), (xc - 0.3, yh), "ds", (xc, yh + 0.3),
                        (xc, hy - 0.4), "ds", (hx, hy)])
    (px, py), (hx, hy) = UG(18), HG(18)
    g.route(gp(18), [(px, py), (px, 29.6), "ds", (13.35, 30.05), (16.75, 30.05), "ds", (17.05, 30.35),
                     (17.05, hy - 0.4), "ds", (hx, hy)])
    (px, py), (hx, hy) = UG(17), HG(17)
    g.route(gp(17), [(px, py), (px, 30.05), "ds", (12.8, 30.35), (16.45, 30.35), "ds", (16.75, 30.65),
                     (16.75, 45.5), "ds", (18.34, hy), (hx, hy)])
    (px, py), (hx, hy) = UG(16), HG(16)  # GPIO16 は取付穴 H2 を右に避ける
    g.route(gp(16), [(px, py), (px, 30.5), "ds", (12.25, 30.65), (16.15, 30.65), "ds", (16.45, 30.95),
                     (16.45, 46.0), "ds", (17.8, 47.35), (17.8, hy - 0.5), "ds", (hx, hy)])

    # ================================================= 水晶
    y1 = lambda n: P("Y1", n)
    px, py = U(21)
    g.route("XIN", [(px, py), (px, 29.2), "ds", (9.3, 29.6), (9.3, 31.6), "ds", (8.6, 32.3), (8.6, 34.0), "ds", (8.1, 34.5), y1(1)])
    g.route("XIN", [y1(1), P("C21", 1)], w=0.2)
    px, py = U(22)
    g.route("XOUT", [(px, py), (px, 30.2), "sd", P("R6", 2)])
    g.route("XOUT_R", [P("R6", 1), (10.0, 32.6)], w=0.2)
    g.route("XOUT_R", [y1(3), P("C22", 1)], w=0.2)

    # ================================================= SWD
    px, py = U(24)
    g.route("SWCLK", [(px, py), (px, 31.0), "ds", (12.3, 32.4), (12.3, 36.0), "ds", (7.96, 40.34), (7.96, 49.39)])
    px, py = U(25)
    g.route("SWDIO", [(px, py), (px, 31.0), "ds", (12.6, 32.3), (12.6, 48.0), "ds", (13.04, 48.44), (13.04, 49.39)])

    # ================================================= チップ真下のビア（パッド列と中央パッドの間）
    def inward(pin, net, w=0.2):
        x, y = U(pin)
        if x < 8:
            v = (8.125, y)
        elif x > 13:
            v = (12.875, y)
        elif y < 23:
            v = (x, 22.725)
        else:
            v = (x, 27.475)
        g.seg(net, (x, y), v, w)
        g.via(net, *v)
        return v

    inward(6, "+1V1")
    inward(11, "+3V3")
    inward(20, "+3V3")
    inward(23, "+1V1")
    inward(38, "+3V3")
    inward(49, "+3V3")
    x, y = U(26)  # RUN のビアは 1.1V ベタの通り道を残すため少し外寄り
    v_run = g.via("RUN", x, 27.6)
    g.seg("RUN", (x, y), v_run, 0.15)
    v_g24 = inward(36, gp(24), 0.15)
    x, y = U(43)
    v_g29 = g.via(gp(29), 12.875, 23.3)
    g.route(gp(29), [(x, y), (13.3, y), "-", (13.1, 23.3), v_g29])
    for pin in (53, 54):  # QSPI_IOVDD / USB_OTP_VDD は 1 個のビアを共有
        x, y = U(pin)
        g.route("+3V3", [(x, y), (x, 22.35), "-", (10.3, 22.725)], w=0.2)
    g.via("+3V3", 10.3, 22.725)
    x, y = U(47)  # VREG_PGND もチップ下ビアで GND プレーンへ
    g.seg("GND", (x, y), (x, 22.6), 0.2)
    g.via("GND", x, 22.6)
    for dx, dy in ((-0.95, -0.95), (0.95, -0.95), (-0.95, 0.95), (0.95, 0.95)):
        g.via("GND", 10.5 + dx, 25.1 + dy)

    def gv(x, y, frm=None, w=0.25, net="GND"):
        if frm is not None:
            g.route(net, [frm, "-", (x, y)], w=w)
        g.via(net, x, y)

    # ================================================= チップ周りのデカップリング
    g.route("+3V3", [U(1), (6.65, 22.3), "-", P("C8", 1)], w=0.2)
    gv(5.55, 21.95, P("C8", 1), net="+3V3")
    gv(5.55, 20.87, P("C8", 2))
    g.route("+3V3", [U(11), (6.5, 26.3), "-", P("C9", 1)], w=0.2)
    gv(3.85, 26.55, P("C9", 2))
    gv(5.92, 29.4, P("C14", 1), net="+1V1")
    gv(6.88, 29.4, P("C14", 2))
    gv(5.42, 32.6, P("C10", 1), net="+3V3")
    gv(6.38, 32.6, P("C10", 2))
    g.route("+3V3", [U(30), (13.3, 28.95), "-", P("C11", 1)], w=0.2)
    gv(13.72, 29.55, P("C11", 1), net="+3V3")
    gv(15.7, 28.9, P("C11", 2))
    x, y = U(39)
    g.route("+1V1", [(x, y), (14.5, y), "-", (14.6, 24.6), (14.9, 24.6), P("C16", 1)], w=0.2)
    g.via("+1V1", 14.9, 24.6)
    x, y = U(45)
    g.route("+3V3", [(x, y), (14.75, 22.3), "-", P("C13", 1)], w=0.2)
    g.via("+3V3", 14.75, 22.3)

    # ================================================= LED (GPIO25) と GPIO23 のビア
    g.route(gp(25), [UG(25), P("R9", 1)])
    g.route("LED_A", [P("R9", 2), P("D2", 2)], w=0.25)
    g.route("GND", [P("D2", 1), (17.89, 25.25), "-", (17.6, 24.9), "-", (17.3, 24.6)], w=0.25)
    g.route("GND", [P("C16", 2), (17.3, 24.6)], w=0.25)
    g.via("GND", 17.3, 24.6)
    v_g23 = g.via(gp(23), 16.0, 26.6)
    g.route(gp(23), [UG(23), (15.7, 26.3), "-", v_g23])

    # ================================================= ADC 基準 (ADC_AVDD = ADC_VREF)
    x, y = U(44)
    g.route("ADC_VREF", [(x, y), (14.35, y), "ds", (14.55, 22.9), (16.9, 22.9), "ds", (17.3, 22.5), (17.3, 16.45), "ds",
                         (18.2, 15.55), (18.2, 14.5), "ds", J(35)])
    g.route("ADC_VREF", [P("C18", 1), (16.45, 22.9)], w=0.25)
    g.route("ADC_VREF", [P("R8", 2), P("C19", 1)], w=0.25)
    g.route("ADC_VREF", [P("C19", 1), (17.3, 19.82)], w=0.15)
    gv(16.5, 17.05, P("R8", 1), net="+3V3")
    g.route("GND", [P("C19", 2), (16.5, 21.15), "-", P("C18", 2)], w=0.25)
    g.via("GND", 16.5, 21.15)
    g.route("GND", [P("C13", 2), (16.1, 21.65), "-", P("C18", 2)], w=0.25)

    # ================================================= コア電源 (内蔵 SMPS)
    x, y = U(48)
    g.route("VREG_LX", [(x, y), P("L2", 2)], w=0.14)
    g.route("+1V1", [P("L2", 1), P("C6", 1)], w=0.4)
    g.route("+1V1", [(12.0, 17.775), (11.6, 17.775), "ds", (11.45, 17.925), (11.45, 20.9), "ds", (11.7, 21.15), U(50)])
    gv(13.62, 17.0, P("C6", 1), net="+1V1", w=0.3)
    gv(12.6, 16.95, (12.6, 17.6), net="+1V1", w=0.3)
    gv(15.25, 17.775, P("C6", 2))
    g.route("+3V3", [U(49), P("C5", 1)], w=0.2)
    g.route("GND", [U(47), P("C5", 2)], w=0.2)
    x, y = U(46)
    g.route("VREG_AVDD", [(x, y), (13.3, 21.5), "-", (13.6, 21.2), (13.6, 20.6), "-", P("C7", 1)], w=0.2)
    g.route("VREG_AVDD", [P("C7", 1), P("R7", 2)], w=0.2)
    gv(15.45, 19.3, P("R7", 1), net="+3V3")
    gv(15.45, 20.3, P("C7", 2))

    # ================================================= QSPI Flash / BOOTSEL
    f = lambda n: P("U2", n)
    x, y = f(3)
    g.route("QSPI_SD2", [(x, y), (5.75, y), (5.75, 19.35), "ds", (6.05, 19.65), (8.2, 19.65), "ds", (8.5, 19.95), U(58)])
    x, y = f(2)
    g.route("QSPI_SD1", [(x, y), (5.45, y), (5.45, 19.65), "ds", (5.75, 19.95), (7.8, 19.95), "ds", (8.1, 20.25), U(59)])
    x, y = f(1)
    g.route("QSPI_SS", [(x, y), (5.15, y), (5.15, 19.95), "ds", (5.45, 20.25), (7.4, 20.25), "ds", (7.7, 20.55), U(60)])
    g.route("QSPI_SD0", [f(5), "sd", (8.9, 20.3), U(57)])
    x, y = f(6)
    g.route("QSPI_SCLK", [(x, y), (10.05, y), (10.05, 20.2), "ds", (9.3, 20.95), U(56)])
    x, y = f(7)
    g.route("QSPI_SD3", [(x, y), (10.35, y), (10.35, 20.6), "ds", (9.7, 21.25), U(55)])
    g.route("+3V3", [f(8), P("C20", 1)], w=0.25)
    gv(10.0, 16.45, P("C20", 1), net="+3V3")
    g.route("GND", [f(4), (7.9, 19.05)], w=0.2)
    g.route("GND", [P("C20", 2), "-", (7.9, 16.9), (7.9, 17.6)], w=0.2)
    gv(7.65, 16.45, P("C20", 2))
    x, y = P("R5", 1)
    g.route("QSPI_SS", [(x, y), (x, 17.55)])
    g.route("BOOTSEL", [P("R5", 2), "-", (6.2, 14.3)], w=0.2)
    x, y = P("SW1", 2)
    gv(x, 12.2, (x, y))

    # ================================================= USB Type-C
    u = lambda n: P("J1", n)
    DP, DM = "USB_CONN_DP", "USB_CONN_DM"
    g.route(DM, [(10.25, 6.7), (10.25, 6.15), (11.25, 6.15), (11.25, 6.7)], w=0.2)   # A7-B7 はパッドの奥側でつなぐ
    g.route(DP, [(9.75, 7.7), (9.75, 8.35), (10.75, 8.35), (10.75, 7.7)], w=0.2)     # A6-B6 は手前側でつなぐ
    g.route(DP, [(10.35, 8.35), P("R1", 1)], w=0.2)
    g.route(DM, [(11.25, 7.7), (11.25, 9.4), "ds", P("R2", 1)], w=0.2)
    x, y = P("R1", 2)
    g.route("USB_DP", [(x, y), (x, 11.5), "ds", (10.75, 11.9), (10.75, 20.4)], w=0.2)
    g.route("USB_DP", [(10.75, 20.4), (10.75, 21.0), "ds", (10.9, 21.15), U(52)])
    x, y = P("R2", 2)
    g.route("USB_DM", [(x, y), (x, 11.5), "ds", (11.1, 11.75), (11.1, 20.4)], w=0.2)
    g.route("USB_DM", [(11.1, 20.4), (11.1, 20.95), "ds", (11.3, 21.15), U(51)])
    g.route("CC1", [(11.75, 7.7), (11.75, 8.2), "ds", (12.2, 8.65), P("R3", 1)], w=0.2)
    g.route("CC2", [(8.75, 7.7), P("R4", 1)], w=0.2)
    gv(8.75, 10.5, P("R4", 2))
    gv(12.4, 10.4, P("R3", 2))
    g.route("GND", [(12.4, 10.4), P("C1", 2)], w=0.3)
    gv(12.3, 12.3, P("C1", 2))
    g.route("GND", [(7.25, 7.0), (6.5, 7.0)], w=0.4)       # GND ピンをシールド脚へ
    g.route("GND", [(13.75, 7.0), (14.5, 7.0)], w=0.4)

    # ================================================= VBUS → D1 → VSYS → TPS63001 → +3V3
    g.route("VBUS", [(12.95, 7.7), (12.95, 8.35), (15.55, 8.35), "ds", (15.85, 8.05), (15.85, 1.6), "ds", (16.2, 1.25), P("D1", 2)], w=0.4)
    g.route("VBUS", [P("D1", 2), (18.6, 1.25), "-", J(40)], w=0.5)
    g.via("VBUS", 12.95, 8.5)
    g.route("VBUS", [(8.05, 7.7), "-", (7.95, 8.55)], w=0.3)
    g.via("VBUS", 7.95, 8.55)
    g.route("VBUS", [(7.95, 8.55), (12.95, 8.55), "-", (12.95, 8.5)], w=0.3, layer=B)
    g.route("VSYS", [P("D1", 1), (18.6, 4.05), "-", J(39)], w=0.5)
    g.route("VSYS", [P("D1", 1), "-", (17.25, 4.4), (17.25, 8.6), "ds", (16.82, 9.03), (14.1, 9.03), (14.1, 11.0)], w=0.4)
    x, y = P("R10", 1)
    g.route("VSYS", [(x, y), (17.25, y)], w=0.2)
    x, y = P("R10", 2)
    g.route("3V3_EN", [(x, y), (x, 8.19), "ds", J(37)], w=0.2)
    s3 = lambda n: P("U3", n)
    g.route("VSYS", [(14.2, 11.3), "-", (14.6, 11.7), s3(5)], w=0.24)
    g.route("BB_L1", [s3(4), (s3(4)[0], 10.8)], w=0.24)
    g.route("BB_L2", [s3(2), (s3(2)[0], 10.8)], w=0.24)
    g.route("GND", [s3(3), (s3(3)[0], 12.9)], w=0.24)
    g.route("GND", [s3(9), (s3(9)[0], 13.5)], w=0.24)
    g.via("GND", 15.1, 13.2)
    g.via("GND", 16.1, 13.2)
    g.route("+3V3", [s3(1), "-", P("C3", 1)], w=0.24)
    g.route("+3V3", [P("C3", 1), (18.5, 11.575), "-", J(36)], w=0.5)
    x, y = s3(10)
    g.route("+3V3", [(x, y), (x, 15.0), "ds", (16.75, 15.15), (17.3, 15.15), "ds", (17.55, 14.9), (17.55, 11.8)], w=0.15)
    gv(18.0, 12.75, (17.55, 12.0), net="+3V3", w=0.25)
    gv(18.15, 10.0, P("C3", 2))
    v_en = g.via("3V3_EN", 14.35, 15.3)
    g.route("3V3_EN", [s3(6), (s3(6)[0], 14.85), "-", v_en], w=0.15)
    v_ps = g.via(gp(23), 15.1, 15.75)
    g.route(gp(23), [s3(7), v_ps], w=0.15)
    v_vina = g.via("VSYS", 15.75, 15.3)
    g.route("VSYS", [s3(8), (s3(8)[0], 14.9), "-", v_vina], w=0.15)
    g.via("VSYS", 15.6, 9.03)

    # ================================================= 分圧 (VBUS 検出 / VSYS 測定)
    g.route(gp(24), [P("R12", 2), P("R13", 1)], w=0.2)
    v24 = g.via(gp(24), 4.0, 3.6)
    v_vbus = g.via("VBUS", 4.0, 1.0)
    g.route("VBUS", [v_vbus, P("R12", 1)], w=0.25)
    gv(4.0, 6.2, P("R13", 2))
    g.route(gp(29), [P("R14", 2), P("R15", 1)], w=0.2)
    v29 = g.via(gp(29), 7.75, 10.5)
    g.route(gp(29), [(7.1, 10.5), v29], w=0.2)
    v_vsys = g.via("VSYS", 7.25, 8.45)
    g.route("VSYS", [v_vsys, "-", P("R14", 1)], w=0.2)
    gv(8.05, 12.0, P("R15", 2))

    # ================================================= 水晶まわりの GND
    gv(5.52, 35.4, P("C21", 2))
    gv(9.7, 35.6, P("Y1", 2))
    g.route("GND", [P("Y1", 4), "-", (6.38, 32.6)], w=0.25)
    gv(11.73, 33.7, P("C22", 2))

    # ================================================= 裏面 (B.Cu) の配線
    g.route("RUN", [v_run, "ds", (11.85, 27.75), (18.3, 27.75), "ds", J(30)], layer=B)
